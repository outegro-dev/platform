export const techLexicon: TechEntry[] = Object.entries(raw).flatMap(
  ([category, terms]) =>
    Object.entries(terms).map(([canonical, aliases]) => ({
      canonical,
      aliases,
      category,
    })),
);

/** Loose spelling: case, spaces, dots and dashes do not matter. */
const loose = (term: string) =>
  term
    .trim()
    .toLowerCase()
    .replace(/[\s._-]+/g, "");

const looseIndex = new Map<string, string>();
for (const entry of techLexicon)
  for (const spelling of [
    entry.canonical,
    ...entry.aliases.map((alias) => alias.replace(/^=/, "")),
  ]) {
    const key = loose(spelling);
    if (key && !looseIndex.has(key)) looseIndex.set(key, entry.canonical);
  }

/** A technology name as the lexicon writes it: "K8s" → "Kubernetes", "React.js" → "React"; `null` when unknown. */
export function normalizeTech(term: string): string | null {
  return looseIndex.get(loose(term)) ?? null;
}

export const categoryOf = (canonical: string): string | null =>
  techLexicon.find((entry) => entry.canonical === canonical)?.category ?? null;

type Matcher = { canonical: string; pattern: RegExp; length: number };

const escapeRegex = (value: string) =>
  value.replace(/[.*+?^${}()|[\]\\/]/g, "\\$&");
/** Words after "Go" or "Spring" that make them English, not technologies. */
const notTech: Record<string, RegExp> = {
  Go: /^\s+(?:to|above|beyond|live|further|ahead|deeper|the|from|out|back|through|over|far|get|hand)\b/,
  Spring: /^\s+(?:\d|semester|term|break|internship|season)/i,
};

let matchers: Matcher[] | null = null;
function allMatchers(): Matcher[] {
  matchers ??= techLexicon
    .flatMap((entry) =>
      entry.aliases.map((alias) => {
        const exact = alias.startsWith("=");
        const text = alias.replace(/^=/, "");
        return {
          canonical: entry.canonical,
          length: text.length,
          pattern: new RegExp(
            // "PostgreSQL/Redis" names both; "ASP.NET" is not ".NET", "NoSQL" is not "SQL".
            `(?<![\\w.+#@-])${escapeRegex(text)}(?![\\w+#-]|\\.\\w)`,
            exact ? "g" : "gi",
          ),
          guard: exact ? notTech[text] : undefined,
        };
      }),
    )
    .map(({ canonical, pattern, length, guard }) => ({
      canonical,
      length,
      pattern: guard ? withGuard(pattern, guard) : pattern,
    }));
  return matchers;
}

function withGuard(pattern: RegExp, guard: RegExp): RegExp {
  return new RegExp(
    `${pattern.source}(?!${guard.source.replace(/^\^/, "")})`,
    pattern.flags,
  );
}

export type TechHit = { canonical: string; index: number; text: string };

/**
 * Every technology mention in a text. Overlapping spellings resolve to the
 * longest one ("React Native" is not also "React").
 */
export function findTechnologies(text: string): TechHit[] {
  const hits: (TechHit & { end: number })[] = [];
  for (const matcher of allMatchers()) {
    matcher.pattern.lastIndex = 0;
    for (const match of text.matchAll(matcher.pattern)) {
      const index = match.index ?? 0;
      hits.push({
        canonical: matcher.canonical,
        index,
        text: match[0],
        end: index + match[0].length,
      });
    }
  }
  hits.sort((a, b) => a.index - b.index || b.end - b.index - (a.end - a.index));
  const kept: TechHit[] = [];
  let reach = -1;
  for (const hit of hits) {
    if (hit.index < reach) continue;
    kept.push({ canonical: hit.canonical, index: hit.index, text: hit.text });
    reach = hit.end;
  }
  return kept;
}
