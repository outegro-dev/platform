import type { CvDocument } from "@outegro/contracts/atelier";
import {
  cleanText,
  plainText,
  texEscape,
  texLinkText,
  texRich,
  texUrl,
} from "./latex.js";

/** A piece of text whose printed lines the fitting loop needs. */
export type MeasuredBlock = { id: string; text: string };

export type CvContent = {
  /** content.tex for cv.tex (`\def\ContentFile{content}`). */
  tex: string;
  /** summary:<i>, skill:<i>, bullet:<bullet id>, in print order. */
  blocks: MeasuredBlock[];
};

/** `\item` reads a following `[` as its optional label; `{}` stops that. */
const itemText = (tex: string) => (tex.startsWith("[") ? `{}${tex}` : tex);

const skillText = (skill: CvDocument["skills"][number]) =>
  `${cleanText(skill.label)}: ${skill.items.map(cleanText).join(", ")}`;

function pdfMetadata(doc: CvDocument) {
  const title =
    cleanText(doc.pdf.title) ||
    `${cleanText(doc.name)} - ${plainText(doc.headline)} - CV`;
  const keywords = doc.pdf.keywords.map(cleanText).filter(Boolean).join(", ");
  return [
    "\\hypersetup{",
    `  pdftitle={${texEscape(title)}},`,
    `  pdfauthor={${texEscape(doc.name)}},`,
    `  pdfsubject={${texEscape(doc.pdf.subject)}},`,
    `  pdfkeywords={${texEscape(keywords)}}`,
    "}",
  ];
}

function header(doc: CvDocument) {
  const lines = [
    "\\cvheader",
    `  {${texEscape(doc.name)}}`,
    `  {${texEscape(doc.location)}}`,
    `  {${texEscape(doc.phoneDisplay)}}{${doc.phoneDigits}}`,
    `  {${texEscape(doc.headline)}}`,
    `  {${texEscape(doc.stack)}}`,
  ];
  if (doc.links.length) {
    const links = doc.links.map(
      (link) => `  \\cvlink{${texUrl(link.url)}}{${texLinkText(link.text)}}`,
    );
    lines.push(`\\cvlinks{%\n${links.join("\\linksep\n")}}`);
  }
  return lines;
}

function summary(doc: CvDocument) {
  const [first = "", second = ""] = doc.summary.map(texRich);
  // One paragraph: the second argument stays empty; cv.tex then leaves out
  // the gap between the paragraphs too.
  return [
    "\\cvsection{Summary}",
    `\\cvsummary{%\n${first}%\n}{%\n${second}${second ? "%\n" : ""}}`,
  ];
}

function skills(doc: CvDocument) {
  return [
    "\\cvsection{Skills}",
    "\\begin{cvskills}",
    ...doc.skills.map(
      (skill) =>
        `\\cvskill{${texEscape(skill.label)}}{${texEscape(skill.items.map(cleanText).join(", "))}}`,
    ),
    "\\end{cvskills}",
  ];
}

function experience(doc: CvDocument) {
  const lines = ["\\cvsection{Professional Experience}"];
  for (const job of doc.jobs) {
    lines.push(
      "",
      `\\cvjob{${texEscape(job.title)}}{${texEscape(job.company)}}{${texEscape(job.dates)}}{${texEscape(job.location)}}{${texEscape(job.description)}}`,
    );
    if (!job.bullets.length) continue;
    lines.push(
      "\\begin{cvbullets}",
      ...job.bullets.map(
        (bullet) => `  \\item ${itemText(texRich(bullet.text))}`,
      ),
      "\\end{cvbullets}",
    );
  }
  return lines;
}

function education(doc: CvDocument) {
  if (!doc.education.length) return [];
  return [
    "\\cvsection{Education}",
    ...doc.education.map(
      (entry) =>
        `\\cvedu{${texEscape(entry.degree)}}{${texEscape(entry.school)}}{${texEscape(entry.dates)}}`,
    ),
  ];
}

function languages(doc: CvDocument) {
  const named = doc.languages.filter((language) => cleanText(language.name));
  if (!named.length) return [];
  return [
    "\\cvsection{Languages}",
    ...named.map(
      (language) =>
        `\\cvlang{${texEscape(language.name)}}{${texEscape(language.level)}}`,
    ),
  ];
}

/** The blocks the fitting loop shortens, with the text a reader sees. */
export function measuredBlocks(doc: CvDocument): MeasuredBlock[] {
  return [
    ...doc.summary.map((text, index) => ({
      id: `summary:${index}`,
      text: plainText(text),
    })),
    ...doc.skills.map((skill, index) => ({
      id: `skill:${index}`,
      text: skillText(skill),
    })),
    ...doc.jobs.flatMap((job) =>
      job.bullets.map((bullet) => ({
        id: `bullet:${bullet.id}`,
        text: plainText(bullet.text),
      })),
    ),
  ];
}

/** CvDocument → content.tex for the "Minimal violet" layout. */
export function buildContent(doc: CvDocument): CvContent {
  const sections = [
    [
      "% Generated by atelier-tex from a CvDocument; the layout is cv.tex.",
      ...pdfMetadata(doc),
    ],
    header(doc),
    summary(doc),
    skills(doc),
    experience(doc),
    education(doc),
    languages(doc),
  ].filter((section) => section.length);
  return {
    tex: `${sections.map((section) => section.join("\n")).join("\n\n")}\n`,
    blocks: measuredBlocks(doc),
  };
}
